/** 匯出核心邏輯供測試呼叫（測試需驗證真實內容 seed 行為，不重複貼一份內容） */
export async function seedKnowledgeSources(): Promise<{ sourceCount: number; chunkCount: number }> {
  const db = getDb();
  let sourceCount = 0;
  let chunkCount = 0;

  for (const chapter of CHAPTERS) {
    const existing = await db
      .select()
      .from(knowledgeSources)
      .where(eq(knowledgeSources.title, chapter.title))
      .limit(1);
    if (existing[0]) continue;

    const [source] = await db
      .insert(knowledgeSources)
      .values({
        title: chapter.title,
        author: AUTHOR,
        sourceType: "vetted_education",
        status: "draft",
      })
      .returning();

    const chunks = chunkText(chapter.content);
    for (let i = 0; i < chunks.length; i++) {
      await db.insert(knowledgeChunks).values({
        sourceId: source!.id,
        chunkIndex: i,
        content: chunks[i]!,
      });
      chunkCount++;
    }
    sourceCount++;
  }

  return { sourceCount, chunkCount };
}

/** 僅在直接以 CLI 執行本檔時才跑（被測試 import 時不會觸發 process.exit） */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  seedKnowledgeSources()
    .then(({ sourceCount, chunkCount }) => {
      console.log(
        `seeded ${sourceCount} knowledge source(s) (${BOOK_TITLE}), ${chunkCount} chunk(s) (idempotent, status=draft)`,
      );
      process.exit(0);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
